#!/usr/bin/env node
/**
 * 生成前端命令名联合类型 `src/core/ipc/commands.gen.ts`。
 *
 * 来源（与 build.rs 一致）：
 * - 框架命令：`src-tauri/framework-commands.json`（单一事实源）
 * - 插件命令：扫描每个 `plugins/<id>/backend/mod.rs` 的 `#[tauri::command]`
 *
 * 该文件为生成物（已 gitignore），由 package.json 的 prepare/prepare.mjs 触发。
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PLUGINS_DIR = join(ROOT, 'plugins');
const OUT = join(ROOT, 'src', 'core', 'ipc', 'commands.gen.ts');

function readFrameworkCommands() {
  const path = join(ROOT, 'src-tauri', 'framework-commands.json');
  const json = JSON.parse(readFileSync(path, 'utf8'));
  return (json.commands ?? []).map((fullPath) => fullPath.split('::').pop());
}

/** 从形如 `pub async fn foo(` 的行提取 `foo` */
function extractFnName(line) {
  const index = line.indexOf('fn ');
  if (index < 0) return null;
  return line.slice(index + 3).match(/^[A-Za-z0-9_]+/)?.[0] ?? null;
}

function parseCommands(file) {
  const commands = [];
  let pending = false;
  for (const line of readFileSync(file, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (trimmed.startsWith('#[') && trimmed.includes('tauri::command')) {
      const name = extractFnName(trimmed);
      if (name) commands.push(name);
      else pending = true;
      continue;
    }
    if (pending) {
      const name = extractFnName(trimmed);
      if (name) {
        commands.push(name);
        pending = false;
      } else if (trimmed && !trimmed.startsWith('//') && !trimmed.startsWith('#[')) {
        pending = false;
      }
    }
  }
  return commands;
}

function readPluginCommands() {
  const commands = [];
  if (!existsSync(PLUGINS_DIR)) return commands;
  for (const dir of readdirSync(PLUGINS_DIR)) {
    if (dir.startsWith('_') || dir.startsWith('.')) continue;
    const file = join(PLUGINS_DIR, dir, 'backend', 'mod.rs');
    if (existsSync(file)) commands.push(...parseCommands(file));
  }
  return commands;
}

const names = [...new Set([...readFrameworkCommands(), ...readPluginCommands()])].sort();
const union = names.map((name) => `  | '${name}'`).join('\n');
const content =
  '// @generated by scripts/gen-commands.mjs —— 请勿手改。\n' +
  '// 全部已注册命令名（框架 + 插件），供 @/core/ipc 类型约束。\n' +
  `export type CommandName =\n${union};\n`;

writeFileSync(OUT, content);
console.log(`[gen-commands] 已生成 ${names.length} 个命令名 → src/core/ipc/commands.gen.ts`);
